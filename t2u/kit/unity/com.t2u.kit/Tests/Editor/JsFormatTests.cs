            new[] { "0100000000000000", "5e-324", "0", "0.0", "0.00", "0.000" },
            new[] { "ffffffffffffef7f", "1.7976931348623157e+308", "1.7976931348623157e+308", "1.7976931348623157e+308", "1.7976931348623157e+308", "1.7976931348623157e+308" },
