            new[] { "000000000000e03f", "0.5", "1", "0.5", "0.50", "0.500" },
            new[] { "333333333333f73f", "1.45", "1", "1.4", "1.45", "1.450" },
            new[] { "3333333333b32540", "10.85", "11", "10.8", "10.85", "10.850" },
            new[] { "77be9f1a2fdd5e40", "123.456", "123", "123.5", "123.46", "123.456" },
            new[] { "343333333333d33f", "0.30000000000000004", "0", "0.3", "0.30", "0.300" },
            new[] { "50efe2d6e41a4b44", "1e+21", "1e+21", "1e+21", "1e+21", "1e+21" },
