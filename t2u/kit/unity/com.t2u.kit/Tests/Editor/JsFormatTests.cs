            new[] { "713d0ad7a3b02040", "8.345", "8", "8.3", "8.35", "8.345" },
            new[] { "0ad7a3703d0aa73f", "0.045", "0", "0.0", "0.04", "0.045" }
        };

        static double D(string hex)
        {
            var b = new byte[8];
            for (int i = 0; i < 8; i++) b[i] = Convert.ToByte(hex.Substring(i * 2, 2), 16);
            return BitConverter.ToDouble(b, 0);
        }

        [Test]
        public void ToStr_IsJsString()
        {
            foreach (var c in Cases) Assert.AreEqual(c[1], Js.ToStr(D(c[0])), c[1]);
        }

        [Test]
        public void ToFixed_IsJsToFixed()
        {
            foreach (var c in Cases)
                for (int d = 0; d <= 3; d++)
                    Assert.AreEqual(c[2 + d], Js.ToFixed(D(c[0]), d), $"{c[1]}.toFixed({d})");
        }
    }
